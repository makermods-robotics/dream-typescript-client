"""Writes src/casefold.data.ts: Python's `str.casefold()` for every code point it changes (npm run casefold).

Run with any Python 3 (the table is Python's own Unicode database, `unicodedata.unidata_version`). Single code point
folds are written as runs (`start, count, step, delta`: `count` code points from `start`, `step` apart, each folding
to itself plus `delta`); folds to several code points as a map. `src/trained-inputs.ts` compares prompts with it, as
`dream.trained_inputs._plain` does with `casefold()`.
"""

import json
import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "casefold.data.ts"


def main() -> None:
    single, multi = [], {}
    for cp in range(0x110000):
        folded = chr(cp).casefold()
        if folded == chr(cp):
            continue
        if len(folded) == 1:
            single.append((cp, ord(folded) - cp))
        else:
            multi[cp] = folded
    runs: list[list[int]] = []
    for cp, delta in single:
        last = runs[-1] if runs else None
        if last and last[3] == delta and (last[1] == 1 and cp - last[0] in (1, 2) or last[1] > 1 and cp == last[0] + last[1] * last[2]):
            if last[1] == 1:
                last[2] = cp - last[0]
            last[1] += 1
        else:
            runs.append([cp, 1, 1, delta])
    flat = ",".join(str(v) for run in runs for v in run)
    pairs = ",".join(f"[{cp},{json.dumps(text, ensure_ascii=True)}]" for cp, text in multi.items())
    OUT.write_text(
        f"// Generated by scripts/gen_casefold.py from Python {sys.version.split()[0]} str.casefold() (Unicode "
        f"{unicodedata.unidata_version}). Do not edit.\n"
        f"/** Runs of single code point folds: start, count, step, delta. */\n"
        f"export const FOLD_RUNS: readonly number[] = [{flat}];\n"
        f"/** Code points that fold to several. */\n"
        f"export const FOLD_MULTI: ReadonlyArray<readonly [number, string]> = [{pairs}];\n"
    )
    print(f"wrote {OUT}: {len(single)} single folds in {len(runs)} runs, {len(multi)} multiple", file=sys.stderr)


if __name__ == "__main__":
    main()
